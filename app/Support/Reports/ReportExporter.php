<?php

namespace App\Support\Reports;

use App\Models\StoredFile;
use App\Models\User;
use App\Support\Audit;
use App\Support\Documents\DocumentVault;
use Barryvdh\DomPDF\Facade\Pdf;
use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\ShouldAutoSize;
use Maatwebsite\Excel\Concerns\WithHeadings;
use Maatwebsite\Excel\Concerns\WithStyles;
use Maatwebsite\Excel\Concerns\WithTitle;
use Maatwebsite\Excel\Excel;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use RuntimeException;

/**
 * Turns a report into Excel (.xlsx) or PDF bytes.
 *
 * - Exports up to inlineLimit() rows download immediately.
 * - Bigger exports are generated by a queued job, stored encrypted in the
 *   vault and the user is emailed a link only they can open.
 * - PDFs are capped at pdfLimit() rows (dompdf is slow and a 10,000-row PDF
 *   isn't readable anyway) — use Excel for bigger data.
 */
class ReportExporter
{
    /** Rows above which exports are queued (config: portal.reports.inline_limit). */
    public static function inlineLimit(): int
    {
        return (int) config('portal.reports.inline_limit', 2000);
    }

    /** Maximum rows for a PDF (config: portal.reports.pdf_limit). */
    public static function pdfLimit(): int
    {
        return (int) config('portal.reports.pdf_limit', 5000);
    }

    public const MIME = [
        'xlsx' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'pdf' => 'application/pdf',
    ];

    public function __construct(private readonly Excel $excel, private readonly DocumentVault $vault) {}

    public function render(Report $report, array $filters, string $format): string
    {
        return match ($format) {
            'xlsx' => $this->xlsx($report, $filters),
            'pdf' => $this->pdf($report, $filters),
            default => throw new RuntimeException("Unknown format {$format}"),
        };
    }

    public function filename(Report $report, string $format): string
    {
        return 'waveteam-'.str_replace('_', '-', $report->key).'-'.now()->format('Y-m-d-His').'.'.$format;
    }

    /** Generates and stores the export in the vault (owner = $user). */
    public function store(Report $report, array $filters, string $format, User $user): StoredFile
    {
        $bytes = $this->render($report, $filters, $format);

        return $this->vault->storeContents($bytes, $this->filename($report, $format), $user, [self::MIME[$format]]);
    }

    public static function audit(Report $report, array $filters, string $format, int $rows, bool $queued): void
    {
        Audit::log('report.exported', null, meta: [
            'report' => $report->key, 'format' => $format, 'rows' => $rows, 'queued' => $queued,
            'filters' => array_filter($filters, fn ($v) => $v !== null && $v !== ''),
        ]);
    }

    private function xlsx(Report $report, array $filters): string
    {
        $rows = iterator_to_array($report->table($filters), false);

        $export = new class(array_values($report->columns), $rows, $report->title) implements FromArray, ShouldAutoSize, WithHeadings, WithStyles, WithTitle
        {
            public function __construct(private array $headings, private array $rows, private string $title) {}

            public function array(): array
            {
                return $this->rows;
            }

            public function headings(): array
            {
                return $this->headings;
            }

            public function title(): string
            {
                return mb_substr(preg_replace('/[\\\\\/?*\[\]:]/', '', $this->title), 0, 31);
            }

            public function styles(Worksheet $sheet): array
            {
                $sheet->freezePane('A2');

                return [1 => ['font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF']], 'fill' => ['fillType' => 'solid', 'startColor' => ['rgb' => '0F58A2']]]];
            }
        };

        return $this->excel->raw($export, Excel::XLSX);
    }

    private function pdf(Report $report, array $filters): string
    {
        $count = $report->count($filters);
        if ($count > self::pdfLimit()) {
            throw new RuntimeException(__('This report has :n rows — too many for PDF. Please export to Excel.', ['n' => $count]));
        }

        return Pdf::loadView('pdf.report', [
            'report' => $report,
            'filters' => $filters,
            'summary' => $report->summary($filters),
            'rows' => $report->table($filters),
            'company' => config('portal.company'),
            'generatedBy' => auth()->user()?->name,
        ])->setPaper('a4', $report->orientation)->output();
    }
}
