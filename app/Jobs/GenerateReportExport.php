<?php

namespace App\Jobs;

use App\Models\User;
use App\Notifications\TemplatedNotification;
use App\Support\Reports\ReportExporter;
use App\Support\Reports\ReportRegistry;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;
use Illuminate\Support\Facades\Auth;

/**
 * Large report exports run in the background; the requester is emailed a
 * private download link (the file is encrypted in the vault, owned by them).
 */
class GenerateReportExport implements ShouldQueue
{
    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    public int $timeout = 600;

    public int $tries = 2;

    public function __construct(
        public readonly int $userId,
        public readonly string $reportKey,
        public readonly array $filters,
        public readonly string $format,
    ) {}

    public function handle(ReportExporter $exporter): void
    {
        $user = User::find($this->userId);

        // Permissions may have changed since the request was queued.
        if (! $user || ! $user->isActive() || ! $user->can('reports.export')) {
            return;
        }

        Auth::setUser($user); // "generated by" on the PDF + audit actor
        $report = ReportRegistry::get($this->reportKey);
        $file = $exporter->store($report, $this->filters, $this->format, $user);

        $user->notify(new TemplatedNotification('report.ready', [
            'report' => $report->title,
            'rows' => number_format($report->count($this->filters)),
            'format' => strtoupper($this->format),
        ], route('reports.download', $file), __('Download report')));
    }
}
