#!/usr/bin/env bash
# Serves the portal through MAMP's Apache at http://localhost:8890 (production-like).
# Idempotent: safe to re-run (e.g. after a MAMP update rewrites httpd.conf).
set -euo pipefail

APP="$(cd "$(dirname "$0")/.." && pwd)"
CONF=/Applications/MAMP/conf/apache/httpd.conf
VHOST=/Applications/MAMP/conf/apache/extra/waveteam-portal.conf
PORT="${PORTAL_PORT:-8890}"
APACHECTL=/Applications/MAMP/Library/bin/apachectl

[ -f "$CONF.waveteam-backup" ] || cp "$CONF" "$CONF.waveteam-backup"
echo "→ Backup of httpd.conf: $CONF.waveteam-backup"

# 1. Laravel needs mod_rewrite.
sed -i '' 's|^#LoadModule rewrite_module modules/mod_rewrite.so|LoadModule rewrite_module modules/mod_rewrite.so|' "$CONF"

# 1b. macOS: php-cgi forks a multi-threaded process; Apple's ObjC runtime then
#     aborts it on the first outbound HTTPS call (e.g. the breached-password
#     check). Standard fix: disable the ObjC fork-safety check for php-cgi.
grep -q "OBJC_DISABLE_INITIALIZE_FORK_SAFETY" "$CONF" || \
  sed -i '' 's|^\([[:space:]]*FastCgiServer /Applications/MAMP/fcgi-bin/php.fcgi -socket httpdFastCGI.sock\)$|\1 -initial-env OBJC_DISABLE_INITIALIZE_FORK_SAFETY=YES|' "$CONF"

# 2. Our own site file, included once at the end of httpd.conf.
mkdir -p "$(dirname "$VHOST")"
cat > "$VHOST" <<CONFEOF
# WaveTeam Portal — generated by deploy/local-mamp.sh (re-run it after MAMP updates)

# SECURITY: the project lives inside htdocs, so block the whole project folder
# on every MAMP site (it would otherwise expose .env, keys, logs and source),
# and allow only the public/ web root.
<Directory "$APP">
    Require all denied
</Directory>
<Directory "$APP/public">
    Options -Indexes +FollowSymLinks +ExecCGI
    AllowOverride All
    Require all granted
</Directory>

Listen $PORT
<VirtualHost *:$PORT>
    ServerName localhost
    DocumentRoot "$APP/public"
    ErrorLog "/Applications/MAMP/logs/waveteam_portal_error.log"
    CustomLog "/Applications/MAMP/logs/waveteam_portal_access.log" common
</VirtualHost>
CONFEOF
grep -q "extra/waveteam-portal.conf" "$CONF" || printf '\n# WaveTeam Portal\nInclude %s\n' "$VHOST" >> "$CONF"

echo "→ Checking Apache config"
"$APACHECTL" -t

echo "→ Preparing app (production mode, caches)"
cd "$APP"
PHP=/Applications/MAMP/bin/php/php8.3.30/bin/php
npm run build --silent
"$PHP" artisan optimize:clear >/dev/null
"$PHP" artisan optimize >/dev/null
"$PHP" artisan filament:optimize >/dev/null 2>&1 || true

echo "→ Restarting Apache"
"$APACHECTL" -k restart
sleep 2
echo "✓ Portal: http://localhost:$PORT   (admin: http://localhost:$PORT/admin)"
