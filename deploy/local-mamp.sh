#!/usr/bin/env bash
# Serves the portal through MAMP's Apache at http://localhost:8890/app,
# laid out like the live HostGator account:
#   site root  = a stand-in for WordPress (public_html)
#   /app       = symlink to this project's public/ folder
# Set APP_URL=http://localhost:8890/app in .env.
# Idempotent: safe to re-run (e.g. after a MAMP update rewrites httpd.conf).
set -euo pipefail

APP="$(cd "$(dirname "$0")/.." && pwd)"
CONF=/Applications/MAMP/conf/apache/httpd.conf
VHOST=/Applications/MAMP/conf/apache/extra/waveteam-portal.conf
PORT="${PORTAL_PORT:-8890}"
APACHECTL=/Applications/MAMP/Library/bin/apachectl
SITE="${PORTAL_SITE_ROOT:-/Applications/MAMP/waveteam-site}"   # stands in for public_html

[ -f "$CONF.waveteam-backup" ] || cp "$CONF" "$CONF.waveteam-backup"
echo "→ Backup of httpd.conf: $CONF.waveteam-backup"

# 1. Laravel needs mod_rewrite.
sed -i '' 's|^#LoadModule rewrite_module modules/mod_rewrite.so|LoadModule rewrite_module modules/mod_rewrite.so|' "$CONF"

# 1b. macOS: php-cgi forks a multi-threaded process; Apple's ObjC runtime then
#     aborts it on the first outbound HTTPS call (e.g. the breached-password
#     check). Standard fix: disable the ObjC fork-safety check for php-cgi.
grep -q "OBJC_DISABLE_INITIALIZE_FORK_SAFETY" "$CONF" || \
  sed -i '' 's|^\([[:space:]]*FastCgiServer /Applications/MAMP/fcgi-bin/php.fcgi -socket httpdFastCGI.sock\)$|\1 -initial-env OBJC_DISABLE_INITIALIZE_FORK_SAFETY=YES|' "$CONF"

# 2. Stand-in for public_html: a fake WordPress (with WordPress's own
#    .htaccess rules) at the root, and the portal at /app via a symlink.
mkdir -p "$SITE"
cat > "$SITE/index.php" <<'PHPEOF'
<?php // Stand-in for the WordPress site (local testing only) — generated by deploy/local-mamp.sh
if (! in_array(strtok($_SERVER['REQUEST_URI'], '?'), ['/', '/index.php'], true)) { http_response_code(404); }
?><!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Local test site</title>
<style>body{font-family:system-ui,sans-serif;max-width:640px;margin:48px auto;padding:0 16px;color:#1f2937}h1{color:#0b3b6f}a.btn{display:inline-block;margin:6px 8px 6px 0;padding:10px 16px;border-radius:8px;background:#0f58a2;color:#fff;text-decoration:none}p.note{color:#6b7280;font-size:14px}</style></head><body>
<h1>Local test of www.waveteam.lk</h1>
<p>This page stands in for the <strong>WordPress website</strong>. The portal lives under <strong>/app</strong>, exactly as it will on the live site.</p>
<p><a class="btn" href="/app">Portal home</a><a class="btn" href="/app/applicants">Careers (applicants)</a><a class="btn" href="/app/organizations">Request a service</a><a class="btn" href="/app/admin">Admin</a></p>
<p class="note">Local only, never deployed. Live: https://www.waveteam.lk/app</p>
</body></html>
PHPEOF
[ -e "$SITE/.htaccess" ] || cat > "$SITE/.htaccess" <<'HTEOF'
# BEGIN WordPress
<IfModule mod_rewrite.c>
RewriteEngine On
RewriteBase /
RewriteRule ^index\.php$ - [L]
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule . /index.php [L]
</IfModule>
# END WordPress
HTEOF
ln -sfn "$APP/public" "$SITE/app"

# 3. Our own site file, included once at the end of httpd.conf.
mkdir -p "$(dirname "$VHOST")"
cat > "$VHOST" <<CONFEOF
# WaveTeam Portal — generated by deploy/local-mamp.sh (re-run it after MAMP updates)

# SECURITY: the project lives inside htdocs, so block the whole project folder
# on every MAMP site (it would otherwise expose .env, keys, logs and source),
# and allow only the public/ web root.
<Directory "$APP">
    Require all denied
</Directory>
<Directory "$APP/public">
    Options -Indexes +FollowSymLinks +ExecCGI
    AllowOverride All
    Require all granted
</Directory>

<Directory "$SITE">
    Options -Indexes +SymLinksIfOwnerMatch +ExecCGI
    AllowOverride All
    Require all granted
</Directory>

Listen $PORT
<VirtualHost *:$PORT>
    ServerName localhost
    DocumentRoot "$SITE"
    ErrorLog "/Applications/MAMP/logs/waveteam_portal_error.log"
    CustomLog "/Applications/MAMP/logs/waveteam_portal_access.log" common
</VirtualHost>
CONFEOF
grep -q "extra/waveteam-portal.conf" "$CONF" || printf '\n# WaveTeam Portal\nInclude %s\n' "$VHOST" >> "$CONF"

echo "→ Checking Apache config"
"$APACHECTL" -t

echo "→ Preparing app (production mode, caches)"
cd "$APP"
PHP=/Applications/MAMP/bin/php/php8.3.30/bin/php
npm run build --silent
"$PHP" artisan portal:optimize

echo "→ Restarting Apache"
"$APACHECTL" -k restart
sleep 2
echo "✓ Website stand-in: http://localhost:$PORT"
echo "✓ Portal:           http://localhost:$PORT/app   (admin: http://localhost:$PORT/app/admin)"
